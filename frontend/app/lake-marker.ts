export function lakeMarker(color: [number, number, number], active: boolean) {
  const canvas = document.createElement('canvas');
  const size = 112;
  canvas.width = size;
  canvas.height = size;
  const context = canvas.getContext('2d')!;
  const [red, green, blue] = color;
  const tint = `rgb(${red}, ${green}, ${blue})`;
  const light = context.createRadialGradient(41, 32, 2, 58, 55, 46);
  light.addColorStop(0, '#eff8ff');
  light.addColorStop(.32, '#58aaff');
  light.addColorStop(.70, '#164b9b');
  light.addColorStop(1, '#072347');
  context.shadowColor = tint;
  context.shadowBlur = active ? 17 : 9;
  context.beginPath();
  context.arc(56, 53, 39, 0, 2 * Math.PI);
  context.fillStyle = light;
  context.fill();
  context.shadowBlur = 0;
  context.strokeStyle = tint;
  context.lineWidth = active ? 6 : 4;
  context.stroke();
  context.beginPath();
  context.moveTo(56, 92);
  context.lineTo(56, 105);
  context.lineWidth = 3;
  context.stroke();
  context.beginPath();
  context.moveTo(56, 28);
  context.bezierCurveTo(53, 35, 39, 50, 39, 60);
  context.bezierCurveTo(39, 81, 73, 81, 73, 60);
  context.bezierCurveTo(73, 50, 59, 35, 56, 28);
  context.closePath();
  context.fillStyle = '#e8faff';
  context.fill();
  context.beginPath();
  context.moveTo(46, 62);
  context.quadraticCurveTo(54, 55, 62, 62);
  context.quadraticCurveTo(65, 64, 68, 62);
  context.strokeStyle = '#3174c5';
  context.lineWidth = 2.5;
  context.stroke();
  return { id: tint + '-' + active, url: canvas.toDataURL(), width: size, height: size, anchorY: 105 };
}
